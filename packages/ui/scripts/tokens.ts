/// <reference types="node" />
/**
 * Builds the skin from `src/tokens/tokens.json` (W3C Design Tokens):
 *
 * - `src/styles/tokens.css`: custom properties for both themes (`:root`, `.dark`) and the Tailwind
 *   `@theme` blocks that turn them into utilities (`bg-case`, `font-label`, `shadow-raised`…).
 * - `src/tokens/tokens.ts`: the same values, typed, for scripts (motion, effects, canvases).
 * - The contrast table in `DESIGN_SYSTEM.md`, between its `contrast:start` / `contrast:end` markers.
 *
 * Run with `pnpm --filter @orkide/ui tokens`. The outputs are generated: edit the JSON, not them.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path: string): string =>
  readFileSync(new URL(path, root), "utf-8");
const write = (path: string, text: string): void =>
  writeFileSync(new URL(path, root), text);

interface Token {
  $value: string | number | string[];
  $description?: string;
  $extensions?: { dark?: string };
}
type Group = Record<string, Token | string>;

const source = JSON.parse(read("src/tokens/tokens.json")) as {
  color: Group;
  font: Record<
    "family" | "size" | "weight" | "stretch" | "tracking" | "leading",
    Group
  >;
  radius: Group;
  shadow: Group;
  layout: Group;
  z: Group;
  motion: Record<"ease" | "duration" | "reduced" | "stagger", Group>;
};

/** The tokens of a group, without its `$type` / `$description` keys. */
const entries = (group: Group): [string, Token][] =>
  Object.entries(group).filter(
    (entry): entry is [string, Token] => !entry[0].startsWith("$")
  );

const value = (token: Token): string =>
  Array.isArray(token.$value)
    ? token.$value
        .map((part) => (part.includes(" ") ? `"${part}"` : part))
        .join(", ")
    : String(token.$value);

const colors = entries(source.color);

/* ── tokens.css ─────────────────────────────────────────────────────────────────────────── */
const light: string[] = [];
const dark: string[] = [];
const inline: string[] = [];
const theme: string[] = [];

for (const [name, token] of colors) {
  light.push(`--o-${name}: ${value(token)};`);
  dark.push(`--o-${name}: ${token.$extensions?.dark ?? value(token)};`);
  inline.push(`--color-${name}: var(--o-${name});`);
}
for (const [name, token] of entries(source.font.family)) {
  light.push(`--o-font-${name}: ${value(token)};`);
  inline.push(`--font-${name}: var(--o-font-${name});`);
}
for (const [name, token] of entries(source.shadow)) {
  light.push(`--o-shadow-${name}: ${value(token)};`);
  inline.push(`--shadow-${name}: var(--o-shadow-${name});`);
}
for (const [name, token] of entries(source.font.stretch)) {
  light.push(`--o-stretch-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.layout)) {
  light.push(`--o-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.z)) {
  light.push(`--o-z-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.motion.duration)) {
  light.push(`--o-dur-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.motion.stagger)) {
  light.push(`--o-stagger-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.motion.reduced)) {
  light.push(`--o-reduced-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.font.size)) {
  theme.push(`--text-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.font.weight)) {
  theme.push(`--font-weight-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.font.tracking)) {
  theme.push(`--tracking-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.font.leading)) {
  theme.push(`--leading-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.radius)) {
  theme.push(`--radius-${name}: ${value(token)};`);
}
for (const [name, token] of entries(source.motion.ease)) {
  light.push(`--o-ease-${name}: ${value(token)};`);
  theme.push(`--ease-${name}: ${value(token)};`);
}

const block = (selector: string, lines: string[]): string =>
  `${selector} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}\n`;

write(
  "src/styles/tokens.css",
  `/* Generated by scripts/tokens.ts from src/tokens/tokens.json. Do not edit by hand. */\n\n${block(
    ":root",
    ["color-scheme: light;", ...light]
  )}\n${block(".dark", ["color-scheme: dark;", ...dark])}\n${block(
    "@theme inline",
    inline
  )}\n${block("@theme", theme)}`
);

/* ── tokens.ts ──────────────────────────────────────────────────────────────────────────── */
const ms = (text: string): number => Number(text.replace(/ms$/u, ""));
const pick = (group: Group): Record<string, string> =>
  Object.fromEntries(
    entries(group).map(([name, token]) => [name, value(token)])
  );
const typed = {
  color: {
    dark: Object.fromEntries(
      colors.map(([name, token]) => [
        name,
        token.$extensions?.dark ?? value(token),
      ])
    ),
    light: Object.fromEntries(
      colors.map(([name, token]) => [name, value(token)])
    ),
  },
  duration: Object.fromEntries(
    entries(source.motion.duration).map(([name, token]) => [
      name,
      ms(value(token)),
    ])
  ),
  ease: pick(source.motion.ease),
  font: pick(source.font.family),
  reduced: Object.fromEntries(
    entries(source.motion.reduced).map(([name, token]) => [
      name,
      ms(value(token)),
    ])
  ),
  stagger: Object.fromEntries(
    entries(source.motion.stagger).map(([name, token]) => [
      name,
      ms(value(token)),
    ])
  ),
};
write(
  "src/tokens/tokens.ts",
  `/* Generated by scripts/tokens.ts from src/tokens/tokens.json. Do not edit by hand. */\n\n/** The skin's tokens, typed. Durations and staggers are milliseconds. */\nexport const tokens = ${JSON.stringify(typed, null, 2)} as const;\n\nexport type ColorToken = keyof typeof tokens.color.light;\n`
);

/* ── Contrast (WCAG 2.2) ────────────────────────────────────────────────────────────────── */
type Rgba = [number, number, number, number];
const parse = (text: string): Rgba => {
  const hex = /^#(?<r>[\da-f]{2})(?<g>[\da-f]{2})(?<b>[\da-f]{2})$/iu.exec(
    text
  )?.groups;
  if (hex) {
    return [
      Number.parseInt(hex.r ?? "", 16),
      Number.parseInt(hex.g ?? "", 16),
      Number.parseInt(hex.b ?? "", 16),
      1,
    ];
  }
  const rgba = /^rgba\((?<r>\d+), (?<g>\d+), (?<b>\d+), (?<a>[\d.]+)\)$/u.exec(
    text
  )?.groups;
  if (!rgba) {
    throw new Error(`Unsupported colour: ${text}`);
  }
  return [Number(rgba.r), Number(rgba.g), Number(rgba.b), Number(rgba.a)];
};
const over = (top: Rgba, bottom: Rgba): Rgba => [
  top[0] * top[3] + bottom[0] * (1 - top[3]),
  top[1] * top[3] + bottom[1] * (1 - top[3]),
  top[2] * top[3] + bottom[2] * (1 - top[3]),
  1,
];
const channel = (c: number): number => {
  const s = c / 255;
  return s <= 0.0405 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = ([r, g, b]: Rgba): number =>
  0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
const ratio = (fg: Rgba, bg: Rgba): number => {
  const [a, b] = [luminance(over(fg, bg)), luminance(bg)].toSorted(
    (x, y) => y - x
  );
  return ((a ?? 0) + 0.05) / ((b ?? 0) + 0.05);
};

/** Every text/background pair the components use, and the minimum it must reach. */
const pairs: [fg: string, bg: string, use: string, min: number][] = [
  ["ink", "case", "Body text, headings", 4.5],
  ["ink", "panel", "Text on raised panels", 4.5],
  ["ink", "deep", "Text in field wells", 4.5],
  ["ink-2", "case", "Secondary text, labels", 4.5],
  ["ink-2", "panel", "Labels on raised panels", 4.5],
  ["placeholder", "deep", "Placeholders in field wells", 4.5],
  ["signal-ink", "case", "Section numbers, hovered indices", 4.5],
  ["signal-ink", "panel", "Accent text on panels", 4.5],
  ["danger", "case", "Error messages", 4.5],
  ["danger", "panel", "Error text on panels (never inside a well)", 4.5],
  ["on-signal", "signal", "Signal keycaps, NOTE badge", 4.5],
  ["on-signal", "signal-hi", "Top of a signal keycap", 4.5],
  ["led", "screen", "Display text", 4.5],
  ["module-ink", "module-deep", "Text on a cartridge", 4.5],
  ["module-ink-2", "module", "Secondary text on a cartridge", 4.5],
  ["focus", "case", "Focus ring on the case (non-text, 3:1)", 3],
  ["focus", "panel", "Focus ring on panels (non-text, 3:1)", 3],
  ["ink", "case", "Rules and keycap outlines (non-text, 3:1)", 3],
];

const palette = { dark: typed.color.dark, light: typed.color.light } as Record<
  "dark" | "light",
  Record<string, string>
>;
const failures: string[] = [];
const rows = pairs.map(([fg, bg, use, min]) => {
  const cells = (["light", "dark"] as const).map((mode) => {
    const r = ratio(
      parse(palette[mode][fg] ?? ""),
      parse(palette[mode][bg] ?? "")
    );
    if (r < min) {
      failures.push(`${mode}: ${fg} on ${bg} = ${r.toFixed(2)} (needs ${min})`);
    }
    return `${r.toFixed(2)}${r < min ? " ⚠️" : ""}`;
  });
  return `| \`${fg}\` on \`${bg}\` | ${use} | ${min}:1 | ${cells[0]} | ${cells[1]} |`;
});
const table = `<!-- contrast:start -->\n| Pair | Used for | Needs | Light | Dark |\n| --- | --- | --- | --- | --- |\n${rows.join("\n")}\n<!-- contrast:end -->`;
const doc = read("DESIGN_SYSTEM.md");
write(
  "DESIGN_SYSTEM.md",
  doc.replace(/<!-- contrast:start -->[\s\S]*<!-- contrast:end -->/u, table)
);

execFileSync(
  "pnpm",
  [
    "exec",
    "oxfmt",
    "packages/ui/src/tokens/tokens.ts",
    "packages/ui/src/styles/tokens.css",
    "packages/ui/DESIGN_SYSTEM.md",
  ],
  { cwd: new URL("../../../", import.meta.url), stdio: "inherit" }
);

process.stdout.write(
  failures.length > 0
    ? `Tokens built. Pairs below their minimum:\n${failures.map((line) => `  - ${line}`).join("\n")}\n`
    : "Tokens built. Every pair meets its minimum.\n"
);
